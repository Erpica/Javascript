// var  => Ya no declaramos variables así
var helloWorld2 = "Hello world"
console.log (helloWorld2)

//      == Estas son las que usamos ==
// let => camelCase
// Solo dentro de su bloque, Que es lo correcto actualmente.
let helloWorld = "Hello world"
console.log (helloWorld)

// const
// También para su bloque pero no se puede cambiar el contenido (en principio...)
const helloWorld3 = "Hola 3"
console.log(helloWorld3)

